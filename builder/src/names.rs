#[expect(
    clippy::unnecessary_wraps,
    reason = "The importer contract uses optional SQLite text values"
)]
pub(crate) fn enum_name(table: &[(i64, &str)], value: i64) -> Option<String> {
    Some(
        table
            .iter()
            .find(|(number, _)| *number == value)
            .map_or_else(|| value.to_string(), |(_, name)| (*name).to_owned()),
    )
}

pub(crate) fn flag_names(table: &[(u32, &str)], mask: u32) -> Option<String> {
    if mask == 0 {
        return None;
    }
    let mut remaining = mask;
    let mut names = Vec::new();
    for &(bit, name) in table {
        if remaining & bit != 0 {
            names.push(name.to_owned());
            remaining &= !bit;
        }
    }
    if remaining != 0 {
        names.push(format!("0x{remaining:08X}"));
    }
    Some(names.join("|"))
}

pub(crate) fn item_subclass(class: i64, subclass: i64) -> Option<String> {
    let table = match class {
        0 => ITEM_SUBCLASS_CONSUMABLE,
        1 => ITEM_SUBCLASS_CONTAINER,
        2 => ITEM_SUBCLASS_WEAPON,
        3 => ITEM_SUBCLASS_GEM,
        4 => ITEM_SUBCLASS_ARMOR,
        5 => ITEM_SUBCLASS_REAGENT,
        6 => ITEM_SUBCLASS_PROJECTILE,
        7 => ITEM_SUBCLASS_TRADE_GOODS,
        8 => ITEM_SUBCLASS_GENERIC,
        9 => ITEM_SUBCLASS_RECIPE,
        10 => ITEM_SUBCLASS_MONEY,
        11 => ITEM_SUBCLASS_QUIVER,
        12 => ITEM_SUBCLASS_QUEST,
        13 => ITEM_SUBCLASS_KEY,
        14 => ITEM_SUBCLASS_PERMANENT,
        15 => ITEM_SUBCLASS_JUNK,
        16 => ITEM_SUBCLASS_GLYPH,
        _ => return Some(subclass.to_string()),
    };
    enum_name(table, subclass)
}
